"""Build price_data.js for Visualization 3 (Property Price Distribution Explorer).

Uses the same cleaning rules as the rest of the project:
  * keep trans_group_en == "Sales"
  * keep instance_date from 2015-01-01 onwards
  * keep meter_sale_price > 0
Result: 51,730 sales.

The output is columnar to keep the file small:
  p = price per m² (AED, rounded to whole dirhams)
  t = property type code per sale  (U = Unit/flat, V = Villa, L = Land, B = Building)
  r = registration code per sale   (O = Off-plan, E = Existing)
  y = year offset per sale as a character ("a" = 2015, "b" = 2016, ...)

Usage:  python prepare_viz3_data.py transactions.csv
"""
import json
import sys

import pandas as pd

TYPE_CODES = {"Unit": "U", "Villa": "V", "Land": "L", "Building": "B"}
REG_CODES = {"Off-Plan Properties": "O", "Existing Properties": "E"}
FIRST_YEAR = 2015

src = sys.argv[1] if len(sys.argv) > 1 else "transactions.csv"
t = pd.read_csv(src, low_memory=False)
print("raw records:", len(t))

s = t[t["trans_group_en"] == "Sales"].copy()
s["date"] = pd.to_datetime(s["instance_date"], errors="coerce")
s = s[s["date"] >= f"{FIRST_YEAR}-01-01"]
print("sales from 2015:", len(s))
s = s[s["meter_sale_price"] > 0]
print("qualifying sales:", len(s))

assert set(s["property_type_en"]) <= set(TYPE_CODES), "unexpected property type"
assert set(s["reg_type_en"]) <= set(REG_CODES), "unexpected registration type"

s = s.sort_values("date")
years = s["date"].dt.year
out = {
    "firstYear": FIRST_YEAR,
    "lastDate": s["date"].max().strftime("%Y-%m-%d"),
    "p": s["meter_sale_price"].round().astype(int).tolist(),
    "t": "".join(s["property_type_en"].map(TYPE_CODES)),
    "r": "".join(s["reg_type_en"].map(REG_CODES)),
    "y": "".join(chr(ord("a") + int(y) - FIRST_YEAR) for y in years),
}
with open("price_data.js", "w") as f:
    f.write("// Generated by prepare_viz3_data.py from transactions.csv. Do not edit by hand.\n")
    f.write("const priceData = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("wrote price_data.js with", len(out["p"]), "sales")
