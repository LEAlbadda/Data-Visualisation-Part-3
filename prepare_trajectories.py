"""Build trajectory_data.js for the Market Trajectories visualization.

Same cleaning as the rest of the project (Sales, from 2015-01-01, price per m² > 0),
then restricted to homes (property_type_en Unit or Villa) so that land plots do not
distort price per m². For Dubai overall and for the 12 communities with the most
home sales, it computes for every year: number of home sales, off-plan share (%)
and median price per m². A year with fewer than MIN_SALES sales is marked
too_few (drawn as a gap, not as a point).

Usage:  python prepare_trajectories.py transactions.csv community_livability.json
"""
import json
import sys

import pandas as pd

TOP_N = 12
MIN_SALES = 20
FIRST_YEAR = 2015

tx_path = sys.argv[1] if len(sys.argv) > 1 else "transactions.csv"
comm_path = sys.argv[2] if len(sys.argv) > 2 else "community_livability.json"

t = pd.read_csv(tx_path, low_memory=False)
s = t[t["trans_group_en"] == "Sales"].copy()
s["date"] = pd.to_datetime(s["instance_date"], errors="coerce")
s = s[(s["date"] >= f"{FIRST_YEAR}-01-01") & (s["meter_sale_price"] > 0)]
homes = s[s["property_type_en"].isin(["Unit", "Villa"])].copy()
homes["year"] = homes["date"].dt.year
homes["offplan"] = homes["reg_type_en"].eq("Off-Plan Properties")
print("qualifying sales:", len(s), "home sales:", len(homes))

communities = {c["comm_num"]: c for c in json.load(open(comm_path))}


def yearly(df):
    g = df.groupby("year").agg(n=("meter_sale_price", "size"),
                               offplan_pct=("offplan", "mean"),
                               median=("meter_sale_price", "median"))
    pts = []
    for year, r in g.iterrows():
        pts.append({"year": int(year), "n": int(r["n"]),
                    "offplan_pct": round(float(r["offplan_pct"]) * 100, 1),
                    "median": int(round(float(r["median"]))),
                    "too_few": bool(r["n"] < MIN_SALES)})
    return pts


entities = [{"id": "dubai", "name": "All of Dubai", "sector": None,
             "total": int(len(homes)), "points": yearly(homes)}]
for comm in homes["comm_num"].value_counts().head(TOP_N).index:
    c = communities[comm]
    sub = homes[homes["comm_num"] == comm]
    entities.append({"id": str(comm), "name": c["community_name"], "sector": c["sector"],
                     "total": int(len(sub)), "points": yearly(sub)})

out = {"lastDate": s["date"].max().strftime("%Y-%m-%d"), "minSales": MIN_SALES, "entities": entities}
with open("trajectory_data.js", "w") as f:
    f.write("// Generated by prepare_trajectories.py from transactions.csv. Do not edit by hand.\n")
    f.write("const trajectoryData = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("wrote trajectory_data.js:", [e["name"] for e in entities])
